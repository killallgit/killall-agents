"""Copy the packaged agents into one project, or remove them, keeping the copies out of Git."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

FACTORY = Path(__file__).resolve().parents[3] / "factory"
FOLDERS = {"claude": Path(".claude/agents"), "codex": Path(".codex/agents"), "cursor": Path(".cursor/agents")}
# The last marker is agent-setup 1.x output, which these copies replace.
MARKERS = ("<!-- killall-agents -->", "# killall-agents\n", "Generated by agent-setup.")
BLOCK = re.compile(r"^# killall-agents:start\n.*?^# killall-agents:end\n", re.MULTILINE | re.DOTALL)
WORKTREE_INCLUDE = Path(".worktreeinclude")
LEGACY_BLOCK = re.compile(r"^# agent-setup:start\n.*?^# agent-setup:end\n\n?", re.MULTILINE | re.DOTALL)


def ours(path: Path) -> bool:
    return path.is_file() and any(marker in path.read_text(encoding="utf-8", errors="ignore") for marker in MARKERS)


def set_block(path: Path, lines: list[str]) -> None:
    """Rewrites our block of root-anchored paths and keeps every other line; no lines drops the block."""
    text = BLOCK.sub("", path.read_text(encoding="utf-8")) if path.is_file() else ""
    if lines:
        text += ("" if not text or text.endswith("\n") else "\n") + "# killall-agents:start\n" + "".join(f"/{line}\n" for line in lines) + "# killall-agents:end\n"
    if text.strip():
        path.write_text(text, encoding="utf-8")
    elif path.is_file():
        path.unlink()


def clear_legacy(dest: Path, exclude: Path) -> None:
    """Undoes agent-setup 1.x: its orchestrator session setting, Cursor rule, and marked blocks."""
    settings = dest / ".claude/settings.json"
    data = json.loads(settings.read_text(encoding="utf-8") or "{}") if settings.is_file() else {}
    if data.get("agent") == "orchestrator":
        del data["agent"]
        settings.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8") if data else settings.unlink()
    if ours(dest / ".cursor/rules/orchestrator.mdc"):
        (dest / ".cursor/rules/orchestrator.mdc").unlink()
    for path in (dest / ".codex/config.toml", exclude, dest / WORKTREE_INCLUDE):
        text = path.read_text(encoding="utf-8") if path.is_file() else ""
        if LEGACY_BLOCK.search(text):
            stripped = LEGACY_BLOCK.sub("", text)
            path.write_text(stripped, encoding="utf-8") if stripped.strip() else path.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dest", type=Path, required=True, help="the project's git root")
    parser.add_argument("--hosts", default="claude,codex,cursor", help="comma-separated: claude, codex, cursor")
    parser.add_argument("--remove", action="store_true", help="remove the copies and their Git entries")
    parser.add_argument("--force", action="store_true", help="replace same-named agents this script did not write")
    args = parser.parse_args()
    dest = args.dest.resolve()
    hosts = [] if args.remove else args.hosts.split(",")
    if unknown := set(hosts) - set(FOLDERS):
        raise SystemExit(f"unknown hosts: {', '.join(sorted(unknown))}")
    copies = {FOLDERS[host] / source.name: source for host in hosts for source in sorted((FACTORY / host).glob("*"))}
    foreign = [str(path) for path in copies if (dest / path).exists() and not ours(dest / path)]
    if foreign and not args.force:
        raise SystemExit("not written by killall-agents, rerun with --force to replace: " + ", ".join(foreign))
    for folder in FOLDERS.values():
        for path in sorted((dest / folder).glob("*")):
            if folder / path.name not in copies and ours(path):
                path.unlink()
                print(f"removed {folder / path.name}")
    for path, source in copies.items():
        (dest / path).parent.mkdir(parents=True, exist_ok=True)
        (dest / path).write_text(source.read_text(encoding="utf-8"), encoding="utf-8")
        print(f"wrote {path}")
    exclude = dest / subprocess.check_output(["git", "-C", str(dest), "rev-parse", "--git-path", "info/exclude"], text=True).strip()
    clear_legacy(dest, exclude)
    for folder in (*FOLDERS.values(), Path(".cursor/rules")):
        for empty in (dest / folder, dest / folder.parent):
            if empty.is_dir() and not empty.is_symlink() and not any(empty.iterdir()):
                empty.rmdir()
    listed = sorted(path.as_posix() for path in copies)
    set_block(exclude, listed + [WORKTREE_INCLUDE.as_posix()] if listed else [])
    # Claude Code copies the ignored files listed here into each worktree it creates.
    set_block(dest / WORKTREE_INCLUDE, listed)


if __name__ == "__main__":
    main()
