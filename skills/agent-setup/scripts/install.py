"""Copy the packaged agents and the orchestrator entry into one project, or remove them, keeping both out of Git."""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
from pathlib import Path

FACTORY = Path(__file__).resolve().parents[3] / "factory"
ROLES = ("planner", "grunt", "builder", "reviewer", "hall-monitor")
NAMES = {"claude": "Claude Code", "codex": "Codex", "cursor": "Cursor"}
FOLDERS = {"claude": Path(".claude/agents"), "codex": Path(".codex/agents"), "cursor": Path(".cursor/agents")}
# The last marker is agent-setup 1.x output, which these copies replace.
MARKERS = ("<!-- killall-agents -->", "# killall-agents\n", "Generated by agent-setup.")
BLOCK = re.compile(r"^(?:# |<!-- )killall-agents:start.*?killall-agents:end(?: -->)?\n\n?", re.MULTILINE | re.DOTALL)
LEGACY_BLOCK = re.compile(r"^# agent-setup:start\n.*?^# agent-setup:end\n\n?", re.MULTILINE | re.DOTALL)
WORKTREE_INCLUDE = Path(".worktreeinclude")
ENTRY = "You are this project's orchestrator when you are the top-level session, not an agent another agent started: load the `orchestrate` skill before multi-step work."
# Each host's personal per-project instructions. Codex has no such file, so its project config carries them.
ENTRIES = {"claude": Path("CLAUDE.local.md"), "codex": Path(".codex/config.toml"), "cursor": Path(".cursor/rules/killall-orchestrator.mdc")}
CURSOR_RULE = f"---\ndescription: This project's orchestrator\nalwaysApply: true\n---\n\n{ENTRY}\n\n<!-- killall-agents -->\n"
CODEX_SETTING = "developer_instructions = '''\n" + ENTRY + "\n'''\n"
# agent-setup 2.0 put this line in the user-wide instructions; the project entry replaces it.
GLOBAL_ENTRY = "When you are the top-level session, not an agent another agent started, and this project has the `planner` and `builder` agents, you are its orchestrator: load the `orchestrate` skill before multi-step work."
# Each host's user-wide folder and the variable that moves it.
HOMES = {"claude": "CLAUDE_CONFIG_DIR", "codex": "CODEX_HOME", "cursor": None}


def ours(path: Path) -> bool:
    return path.is_file() and any(marker in path.read_text(encoding="utf-8", errors="ignore") for marker in MARKERS)


def without_blocks(path: Path) -> str:
    return LEGACY_BLOCK.sub("", BLOCK.sub("", path.read_text(encoding="utf-8"))) if path.is_file() else ""


def set_block(path: Path, body: str, comment: str = "# {}", first: bool = False) -> None:
    """Rewrites our marked block and keeps every other line; an empty body drops the block."""
    text = without_blocks(path)
    if body:
        block = comment.format("killall-agents:start") + "\n" + body + comment.format("killall-agents:end") + "\n"
        if first:
            text = block + ("\n" + text if text.strip() else "")
        else:
            text += ("" if not text or text.endswith("\n") else "\n") + block
    if text.strip():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    elif path.is_file():
        path.unlink()


def home(host: str) -> Path:
    variable = HOMES[host]
    return Path(variable and os.environ.get(variable) or Path.home() / f".{host}")


def clear_legacy(dest: Path) -> None:
    """Undoes agent-setup 1.x's orchestrator session setting and 2.0's user-wide line; set_block strips 1.x's marked blocks."""
    for path in (home("claude") / "CLAUDE.md", home("codex") / "AGENTS.md"):
        text = path.read_text(encoding="utf-8") if path.is_file() else ""
        if GLOBAL_ENTRY in text:
            path.write_text(re.sub(r"\n*^" + re.escape(GLOBAL_ENTRY) + r"$\n?", "\n", text, flags=re.MULTILINE).lstrip("\n"), encoding="utf-8")
    settings = dest / ".claude/settings.json"
    data = json.loads(settings.read_text(encoding="utf-8") or "{}") if settings.is_file() else {}
    if data.get("agent") == "orchestrator":
        del data["agent"]
        settings.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8") if data else settings.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dest", type=Path, required=True, help="the project's git root")
    parser.add_argument("--hosts", default="claude,codex,cursor", help="comma-separated: claude, codex, cursor")
    parser.add_argument("--remove", action="store_true", help="remove the copies, the orchestrator entry, and their Git entries")
    parser.add_argument("--force", action="store_true", help="replace same-named agents this script did not write")
    args = parser.parse_args()
    dest = args.dest.resolve()
    hosts = [] if args.remove else args.hosts.split(",")
    if unknown := set(hosts) - set(FOLDERS):
        raise SystemExit(f"unknown hosts: {', '.join(sorted(unknown))}")
    if shared := [host for host in FOLDERS if (dest / f".{host}").resolve() == home(host).resolve()]:
        raise SystemExit(f"{dest}/.{shared[0]} is the user-wide {NAMES[shared[0]]} folder; run setup in a project's git root")
    copies = {FOLDERS[host] / source.name: source.read_text(encoding="utf-8") for host in hosts for source in sorted((FACTORY / host).glob("*"))}
    if "cursor" in hosts:
        copies[ENTRIES["cursor"]] = CURSOR_RULE
    foreign = [str(path) for path in copies if (dest / path).exists() and not ours(dest / path)]
    if foreign and not args.force:
        raise SystemExit("not written by killall-agents, rerun with --force to replace: " + ", ".join(foreign))
    root_settings = without_blocks(dest / ENTRIES["codex"]).split("\n[", 1)[0]
    if "codex" in hosts and re.search(r"^\s*developer_instructions\s*=", root_settings, re.MULTILINE):
        raise SystemExit(f"{ENTRIES['codex']} already sets developer_instructions; move them to AGENTS.md or leave codex out of --hosts")

    clear_legacy(dest)
    for folder in (*FOLDERS.values(), ENTRIES["cursor"].parent):
        for path in sorted((dest / folder).glob("*")):
            if folder / path.name not in copies and ours(path):
                path.unlink()
    for path, content in copies.items():
        (dest / path).parent.mkdir(parents=True, exist_ok=True)
        (dest / path).write_text(content, encoding="utf-8")
    set_block(dest / ENTRIES["claude"], ENTRY + "\n" if "claude" in hosts else "", "<!-- {} -->")
    set_block(dest / ENTRIES["codex"], CODEX_SETTING if "codex" in hosts else "", first=True)
    for folder in (*FOLDERS.values(), ENTRIES["cursor"].parent):
        for empty in (dest / folder, dest / folder.parent):
            if empty.is_dir() and not empty.is_symlink() and not any(empty.iterdir()):
                empty.rmdir()

    exclude = dest / subprocess.check_output(["git", "-C", str(dest), "rev-parse", "--git-path", "info/exclude"], text=True).strip()
    listed = sorted({*copies, *(ENTRIES[host] for host in hosts)})
    paths = "".join(f"/{path.as_posix()}\n" for path in listed)
    set_block(exclude, paths + f"/{WORKTREE_INCLUDE}\n" if listed else "")
    # Claude Code copies the ignored files listed here into each worktree it creates.
    set_block(dest / WORKTREE_INCLUDE, paths)
    print(summary(dest, hosts, copies))


def summary(dest: Path, hosts: list[str], copies: dict[Path, str]) -> str:
    if not hosts:
        return f"Agents removed from {dest}"
    rows = [f"  {NAMES[host]:<12} {', '.join(sorted((path.stem for path in copies if path.parent == FOLDERS[host]), key=ROLES.index))}" for host in hosts]
    return f"Agents installed in {dest}\n" + "\n".join(rows)


if __name__ == "__main__":
    main()
