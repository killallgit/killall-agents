"""Install the packaged agents into one project or user-wide, or remove them. Run without flags in a terminal to be asked."""

from __future__ import annotations

import argparse
import copy
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import catalog
import picker

FACTORY = Path(__file__).resolve().parents[3] / "factory"
VERSION = json.loads((FACTORY.parent / ".claude-plugin/plugin.json").read_text(encoding="utf-8"))["version"]
ROLES = ("planner", "grunt", "builder", "reviewer", "hall-monitor", "git-janitor", "git-janitor-investigator", "comment-janitor")
NAMES = {"claude": "Claude Code", "codex": "Codex", "cursor": "Cursor"}
# The last marker is agent-setup 1.x output, which these copies replace.
MARKERS = ("<!-- killall-agents -->", "# killall-agents\n", "Generated by agent-setup.")
BLOCK = re.compile(r"^(?:# |<!-- )killall-agents:start.*?killall-agents:end(?: -->)?\n\n?", re.MULTILINE | re.DOTALL)
LEGACY_BLOCK = re.compile(r"^# agent-setup:start\n.*?^# agent-setup:end\n\n?", re.MULTILINE | re.DOTALL)
WORKTREE_INCLUDE = Path(".worktreeinclude")
# agent-setup 2.x also wrote an orchestrator entry in these files; installing or removing strips it.
ENTRIES = {"claude": Path("CLAUDE.local.md"), "codex": Path(".codex/config.toml"), "cursor": Path(".cursor/rules/killall-orchestrator.mdc")}
# Each host's user-wide folder and the variable that moves it.
HOMES = {"claude": "CLAUDE_CONFIG_DIR", "codex": "CODEX_HOME", "cursor": None}


def ours(path: Path) -> bool:
    return path.is_file() and any(marker in path.read_text(encoding="utf-8", errors="ignore") for marker in MARKERS)


def without_blocks(path: Path) -> str:
    return LEGACY_BLOCK.sub("", BLOCK.sub("", path.read_text(encoding="utf-8"))) if path.is_file() else ""


def set_block(path: Path, body: str, comment: str = "# {}", first: bool = False) -> None:
    """Rewrites our marked block and keeps every other line; an empty body drops the block."""
    text = without_blocks(path)
    if body:
        block = comment.format("killall-agents:start") + "\n" + body + comment.format("killall-agents:end") + "\n"
        if first:
            text = block + ("\n" + text if text.strip() else "")
        else:
            text += ("" if not text or text.endswith("\n") else "\n") + block
    if text.strip():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    elif path.is_file():
        path.unlink()


def home(host: str) -> Path:
    variable = HOMES[host]
    return Path(variable and os.environ.get(variable) or Path.home() / f".{host}")


def agents_dir(scope: str, dest: Path, host: str) -> Path:
    return (dest / f".{host}" if scope == "project" else home(host)) / "agents"


@dataclass
class Choices:
    scope: str
    hosts: list[str]
    roles: set[str]
    slugs: set[str]
    models: dict[str, dict[str, str]]
    force: bool = False
    remove: bool = False


def parse_agents(spec: str, slugs: list[str]) -> tuple[set[str], set[str]]:
    """Splits --agents into lane agents and catalog agents; lanes, catalog, all and none are shorthands."""
    roles: set[str] = set()
    picked: set[str] = set()
    for token in filter(None, spec.split(",")):
        if token in ("lanes", "all"):
            roles |= set(ROLES)
        if token in ("catalog", "all"):
            picked |= set(slugs)
        if token in ROLES:
            roles.add(token)
        elif token in slugs:
            picked.add(token)
        elif token not in ("lanes", "catalog", "all", "none"):
            raise SystemExit(f"unknown agent: {token}")
    return roles, picked


def parse_models(entries: list[str]) -> dict[str, dict[str, str]]:
    models = copy.deepcopy(catalog.DEFAULT_MODELS)
    for entry in entries:
        match = re.fullmatch(r"(claude|codex):(opus|sonnet|haiku)=(\S+)", entry)
        if not match:
            raise SystemExit(f"--model takes HOST:TIER=ID, such as codex:sonnet=gpt-6.1-sol, not {entry}")
        models[match[1]][match[2]] = match[3]
    return models


def project_root(given: Path | None) -> Path:
    if given:
        return given.resolve()
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    if top.returncode:
        raise SystemExit("not inside a Git repository; pass --dest or run with --scope user")
    return Path(top.stdout.strip())


def from_flags(args: argparse.Namespace, slugs: list[str]) -> Choices:
    scope = args.scope or "project"
    roles, picked = parse_agents(args.agents or ("catalog" if scope == "user" else "lanes"), slugs)
    # A project gets every tool as before; user-wide, only the tools that already have a folder.
    default = ",".join(h for h in NAMES if scope == "project" or home(h).is_dir()) or "claude"
    hosts = [] if args.remove else (args.hosts or default).split(",")
    if unknown := set(hosts) - set(NAMES):
        raise SystemExit(f"unknown hosts: {', '.join(sorted(unknown))}")
    return Choices(scope, hosts, roles, picked, parse_models(args.model), args.force, args.remove)


def installed(scope: str, dest: Path) -> tuple[set[str], set[str], set[str]]:
    """The hosts, lane agents, and catalog slugs we already wrote in this scope."""
    hosts, stems = set(), set()
    for host in NAMES:
        for path in agents_dir(scope, dest, host).glob("*"):
            if ours(path):
                hosts.add(host)
                stems.add(path.stem)
    return hosts, stems & set(ROLES), {s[len(catalog.PREFIX) :] for s in stems if s.startswith(catalog.PREFIX)}


def ask_choices(args: argparse.Namespace, agents: list[catalog.Agent], dest: Path | None) -> Choices:
    """The multi-select flow. Everything is asked before anything is written."""
    print(f"killall-agents {VERSION}: pick what to install. Type q at any prompt to quit without writing anything.")
    where = f"This project ({dest})" if dest else "This project (not inside a Git repository)"
    scope = picker.ask_one("Where should the agents go?", [("user", "User-wide: every project sees them"), ("project", where)], "user")
    if scope == "project" and not dest:
        raise SystemExit("not inside a Git repository; run from a project or pick user-wide")
    had_hosts, had_roles, had_slugs = installed(scope, dest or Path.cwd())
    present = had_hosts or {host for host in NAMES if home(host).is_dir()} or {"claude"}
    while not (hosts := picker.ask_many("Which tools?", [(h, f"{NAMES[h]}  ({home(h)})", "Hosts") for h in NAMES], present)):
        print("  pick at least one tool")
    options = [(r, r + ("  (Claude Code only)" if r.startswith(("git-janitor", "comment-janitor")) else ""), "Lane agents (per project, used by the orchestrate skill)") for r in ROLES] if scope == "project" else []
    options += [(a.slug, f"{a.meta['name']:<34} {a.meta['model'] + '/' + a.meta['effort']:<14} {'read-only' if a.readonly else 'edits files'}", "Engineering catalog") for a in agents]
    # A rerun starts from what is installed, since the install makes the folders match the selection.
    defaults = had_roles | had_slugs or (set(ROLES) if scope == "project" else {a.slug for a in agents})
    picked = set(picker.ask_many("Which agents?", options, defaults))
    models = copy.deepcopy(catalog.DEFAULT_MODELS)
    tiers = sorted({a.meta["model"] for a in agents if a.slug in picked})
    shown = [h for h in hosts if h in models]
    if tiers and shown:
        print("\nModels for the catalog agents:")
        for host in shown:
            print(f"  {NAMES[host]:<12} " + ", ".join(f"{t} -> {models[host][t]}" for t in tiers))
        if picker.confirm("Change any of these?", False):
            for host in shown:
                for tier in tiers:
                    models[host][tier] = picker.ask_text(f"{NAMES[host]} model for {tier}-tier agents", models[host][tier])
    return Choices(scope, hosts, picked & set(ROLES), picked - set(ROLES), models)


def build_copies(choices: Choices, dest: Path, agents: list[catalog.Agent]) -> dict[Path, str]:
    copies = {}
    for host in choices.hosts:
        folder = agents_dir(choices.scope, dest, host)
        for source in sorted((FACTORY / host).glob("*")):
            if source.stem in choices.roles:
                copies[folder / source.name] = source.read_text(encoding="utf-8")
        for agent in agents:
            if agent.slug in choices.slugs:
                name, content = catalog.render(host, agent, choices.models)
                copies[folder / name] = content
    return copies


def install(choices: Choices, dest: Path, agents: list[catalog.Agent]) -> str:
    scope, project = choices.scope, choices.scope == "project"
    if choices.roles and not project:
        raise SystemExit("the lane agents install per project; use --scope project, or pick catalog agents only")
    if project and (shared := [host for host in NAMES if (dest / f".{host}").resolve() == home(host).resolve()]):
        raise SystemExit(f"{dest}/.{shared[0]} is the user-wide {NAMES[shared[0]]} folder; run setup in a project's git root")
    copies = build_copies(choices, dest, agents)
    foreign = [str(path) for path in copies if path.exists() and not ours(path)]
    if foreign and not choices.force:
        raise SystemExit("not written by killall-agents, rerun with --force to replace: " + ", ".join(foreign))

    folders = [agents_dir(scope, dest, host) for host in NAMES]
    for folder in (*folders, *([dest / ENTRIES["cursor"].parent] if project else [])):
        for path in sorted(folder.glob("*")):
            if path not in copies and ours(path):
                path.unlink()
    for path, content in copies.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if project:
        set_block(dest / ENTRIES["claude"], "", "<!-- {} -->")
        set_block(dest / ENTRIES["codex"], "")
        for folder in (*(dest / f".{host}/agents" for host in NAMES), dest / ENTRIES["cursor"].parent):
            for empty in (folder, folder.parent):
                if empty.is_dir() and not empty.is_symlink() and not any(empty.iterdir()):
                    empty.rmdir()
        exclude = dest / subprocess.check_output(["git", "-C", str(dest), "rev-parse", "--git-path", "info/exclude"], text=True).strip()
        paths = "".join(f"/{path.relative_to(dest).as_posix()}\n" for path in sorted(copies))
        set_block(exclude, paths + f"/{WORKTREE_INCLUDE}\n" if copies else "")
        # Claude Code copies the ignored files listed here into each worktree it creates.
        set_block(dest / WORKTREE_INCLUDE, paths)
    return summary(choices, dest, copies)


def summary(choices: Choices, dest: Path, copies: dict[Path, str]) -> str:
    where = str(dest) if choices.scope == "project" else "the user-wide folders"
    if not choices.hosts:
        return f"Agents removed from {where}"
    rows = []
    for host in choices.hosts:
        folder = agents_dir(choices.scope, dest, host)
        stems = [path.stem for path in copies if path.parent == folder]
        lanes = sorted((s for s in stems if s in ROLES), key=ROLES.index)
        extra = [f"{sum(s.startswith(catalog.PREFIX) for s in stems)} engineering"] if any(s.startswith(catalog.PREFIX) for s in stems) else []
        rows.append(f"  {NAMES[host]:<12} {', '.join(lanes + extra)}")
    return f"Agents installed in {where} (killall-agents {VERSION})\n" + "\n".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dest", type=Path, help="the project's git root (default: the current repository)")
    parser.add_argument("--scope", choices=("project", "user"), help="project (default) or the user-wide folders")
    parser.add_argument("--hosts", help="comma-separated: claude, codex, cursor (default: all for a project, the installed ones user-wide)")
    parser.add_argument("--agents", help="lanes, catalog, all, none, or comma-separated names (default: lanes for a project, catalog user-wide)")
    parser.add_argument("--model", action="append", default=[], metavar="HOST:TIER=ID", help="override a catalog model, e.g. codex:opus=gpt-6-astra")
    parser.add_argument("--yes", action="store_true", help="never prompt")
    parser.add_argument("--interactive", action="store_true", help="prompt even when stdin is not a terminal")
    parser.add_argument("--remove", action="store_true", help="remove the copies and their Git entries")
    parser.add_argument("--force", action="store_true", help="replace same-named agents this script did not write")
    args = parser.parse_args()
    agents = catalog.load()
    asked = args.interactive or (sys.stdin.isatty() and not (args.yes or args.remove or args.scope or args.agents or args.dest))
    try:
        if asked:
            repo = project_root(args.dest) if args.dest or subprocess.run(["git", "rev-parse"], capture_output=True).returncode == 0 else None
            choices = ask_choices(args, agents, repo)
            dest = repo or Path.cwd()
            planned = build_copies(choices, dest, agents)
            clash = [p for p in planned if p.exists() and not ours(p)]
            place = "this project" if choices.scope == "project" else "the user-wide folders"
            print(f"\nWill write {len(planned)} files under {place}." if planned else f"\nNothing selected: the killall-agents copies under {place} will be removed.")
            if clash:
                print("These exist and were not written by killall-agents:\n  " + "\n  ".join(map(str, clash)))
                choices.force = picker.confirm("Replace them?", False)
                if not choices.force:
                    raise picker.Cancelled
            elif not picker.confirm("Install?", True):
                raise picker.Cancelled
        else:
            choices = from_flags(args, [a.slug for a in agents])
            dest = project_root(args.dest) if choices.scope == "project" else Path.cwd()
    except picker.Cancelled:
        raise SystemExit("cancelled, nothing was written") from None
    print(install(choices, dest, agents))


if __name__ == "__main__":
    main()
