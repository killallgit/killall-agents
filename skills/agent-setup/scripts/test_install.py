"""Checks install.py against a throwaway Git repository."""

import os
import subprocess
import sys
import tempfile
from pathlib import Path

INSTALL = Path(__file__).resolve().parent / "install.py"


def run(repo: Path, *args: str, **env: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run([sys.executable, str(INSTALL), "--dest", str(repo), *args], capture_output=True, text=True, env=os.environ | env)


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp, tempfile.TemporaryDirectory() as user:
        # The user-wide folders live in a second directory so the checks never touch the real ones.
        os.environ.update(HOME=user, CLAUDE_CONFIG_DIR=f"{user}/.claude", CODEX_HOME=f"{user}/.codex")
        repo = Path(tmp)
        subprocess.run(["git", "init", "-q", str(repo)], check=True)
        exclude = repo / ".git/info/exclude"
        (repo / ".worktreeinclude").write_text(".env\n")
        (repo / ".claude/agents").mkdir(parents=True)
        (repo / ".claude/agents/orchestrator.md").write_text("old\n\nGenerated by agent-setup.\n")
        (repo / ".claude/agents/mine.md").write_text("the user's own agent\n")
        (repo / "CLAUDE.local.md").write_text("My notes.\n<!-- killall-agents:start -->\nYou are this project's orchestrator\n<!-- killall-agents:end -->\n")
        (repo / ".cursor/rules").mkdir(parents=True)
        (repo / ".cursor/rules/killall-orchestrator.mdc").write_text("rule\n\n<!-- killall-agents -->\n")
        (repo / ".codex").mkdir()
        (repo / ".codex/config.toml").write_text('# killall-agents:start\ndeveloper_instructions = "x"\n# killall-agents:end\n\n[profiles.mine]\nmodel = "y"\n')
        with exclude.open("a") as file:
            file.write("# agent-setup:start\n/.claude/agents/orchestrator.md\n# agent-setup:end\n")

        assert run(repo, CODEX_HOME=str(repo / ".codex")).returncode != 0, "installed into the user-wide Codex folder"
        assert not (repo / ".codex/agents").exists()
        assert run(repo).returncode == 0
        for path in (".claude/agents/builder.md", ".codex/agents/planner.toml", ".cursor/agents/grunt.md"):
            assert (repo / path).is_file(), path
        assert not (repo / ".claude/agents/orchestrator.md").exists(), "old agent-setup output stays"
        assert (repo / ".claude/agents/mine.md").is_file(), "foreign agent removed"
        assert "/.codex/agents/planner.toml\n" in exclude.read_text()
        assert "agent-setup" not in exclude.read_text()
        assert (repo / "CLAUDE.local.md").read_text() == "My notes.\n", "old orchestrator entry stays"
        assert (repo / ".codex/config.toml").read_text() == '[profiles.mine]\nmodel = "y"\n'
        assert not (repo / ".cursor/rules/killall-orchestrator.mdc").exists()
        assert "CLAUDE.local.md" not in exclude.read_text()
        assert (repo / ".worktreeinclude").read_text().startswith(".env\n# killall-agents:start\n/.claude/agents/builder.md\n")
        status = subprocess.run(["git", "-C", str(repo), "status", "--porcelain", "--untracked-files=all"], capture_output=True, text=True).stdout
        assert status == "?? .claude/agents/mine.md\n?? .codex/config.toml\n?? CLAUDE.local.md\n", status

        assert run(repo, "--hosts", "claude").returncode == 0
        assert not (repo / ".codex/agents").exists(), "unselected host kept its copies"
        assert not (repo / ".cursor").exists()

        (repo / ".claude/agents/builder.md").write_text("the user's builder\n")
        refused = run(repo)
        assert refused.returncode != 0 and "--force" in refused.stderr
        assert (repo / ".claude/agents/builder.md").read_text() == "the user's builder\n"
        (repo / ".claude/agents/builder.md").unlink()

        assert run(repo, "--remove").returncode == 0
        assert sorted(p.name for p in (repo / ".claude/agents").iterdir()) == ["mine.md"]
        assert (repo / ".worktreeinclude").read_text() == ".env\n"
        assert not (repo / ".codex/agents").exists()
        assert "killall-agents" not in exclude.read_text()
    print("install checks passed")


if __name__ == "__main__":
    main()
